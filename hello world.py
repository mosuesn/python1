# hello world
print("hello world")

# data types
str("hello") # str
int("3") # int
float("3.14") # float  
bool("True") # bool

print(type("hello")) # <class 'str'>
print(type(3)) # <class 'int'>
print(type(3.14)) # <class 'float'>
print(type(True)) # <class 'bool'>

# variables
width = 6767
height = 1212
print(f"area = {width * height}") # area = 8176404
print(f"perimeter = {2 * (width + height)}") # perimeter = 15958

# operators
print(5 + 3) # 8
print(5 - 3) # 2
print(5 * 3) # 15
print(5 / 3) # 1.6666666666666667
print(5 // 3) # 1
print(5 % 3) # 2
print(5 ** 3) # 125

# comparison operators
print(5 == 3) # False
print(5 != 3) # True
print(5 > 3) # True
print(5 < 3) # False
print(5 >= 3) # True
print(5 <= 3) # False